export async function requestDemoGeneration(payload) {
  await waitForDemo();
  let items;
  if (payload.kind === "topics") {
    items = topicBlueprints.map(([title, angle, audience, hook], index) => ({
      id: `demo-topic-${index + 1}`,
      title,
      angle,
      audience,
      hook,
      reason: `与“${payload.keyword || "当前关键词"}”相关，且具备清晰、可执行的内容结构。`,
    }));
  } else if (payload.kind === "drafts") {
    items = draftBodies.map((body, index) => ({
      id: `demo-draft-${index + 1}`,
      title: ["35℃ 通勤，我只留下这 3 套公式", "十分钟出门的清爽通勤答案", "照片好看不等于真的好穿", "温柔配色，也能穿出职场力量感", "夏日通勤衣橱检查表"][index],
      body,
      coverDirection: "使用低饱和通勤单品静物和清晰信息层级，突出可收藏的搭配公式。",
      topicTitle: payload.selectedTopic?.title || "夏日通勤穿搭",
    }));
  } else if (payload.kind === "coverPrompts") {
    items = promptBlueprints.map(([title, prompt], index) => ({
      id: `demo-prompt-${index + 1}`,
      title,
      prompt,
    }));
  } else {
    throw Object.assign(new Error("演示模式不支持该生成类型。"), { code: "DEMO_BAD_KIND" });
  }

  return { ok: true, items, ...demoMeta("内置内容生成") };
}

export async function requestDemoDecision({ decisionKind, options = [] }) {
  await waitForDemo();
  if (!options.length) {
    throw Object.assign(new Error("演示决策缺少候选内容。"), { code: "DEMO_EMPTY_OPTIONS" });
  }
  const selectedIds = decisionKind === "rag"
    ? options.slice(0, Math.min(3, options.length)).map((item) => item.id)
    : [options[0].id];
  return {
    ok: true,
    selectedIds,
    reason: decisionKind === "rag" ? "优先选择与关键词最相关且信息互补的 3 条样例。" : "选择结构最完整、最适合继续演示的一项。",
    ...demoMeta("内置规则决策"),
  };
}


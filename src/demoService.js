function demoMeta(label) {
  return {
    commandPreview: `DEMO · ${label}`,
    durationMs: DEMO_DELAY_MS,
    generatedAt: new Date().toISOString(),
  };
}

function waitForDemo() {
  return new Promise((resolve) => setTimeout(resolve, DEMO_DELAY_MS));
}

